class SawAgentDev < Formula
  desc "SAW remote agent - dev channel, tracks latest saw-agent-releases pre-release"
  homepage "https://github.com/LenderCom/saw-agent"
  version "0.1.3-dev.2054+ga196c26e"

  # Dev-channel builds cut several times a day from LenderCom/saw-agent-releases
  # (tags dev-vX.Y.Z-dev.N). .github/workflows/bump-formula-dev.yml keeps this pinned to
  # the latest one automatically — see that workflow + script/bump-formula.rb (shared with
  # the stable saw-agent formula; it takes the formula path as its third argument).
  on_macos do
    if Hardware::CPU.arm?
      url "https://github.com/LenderCom/saw-agent-releases/releases/download/dev-v0.1.3-dev.2054/saw-agent_dev-v0.1.3-dev.2054_darwin_arm64.tar.gz"
      sha256 "027b3cd43bfef6735a2f639e5aa2b8a12fe6dafceb2b4ad379fe9ce03e34f685"
    else
      url "https://github.com/LenderCom/saw-agent-releases/releases/download/dev-v0.1.3-dev.2054/saw-agent_dev-v0.1.3-dev.2054_darwin_amd64.tar.gz"
      sha256 "f85bb2b189f7b042ea7141655dc6f754fd915dc6cf922002a5cad81c96fe6d1a"
    end
  end

  on_linux do
    if Hardware::CPU.arm?
      url "https://github.com/LenderCom/saw-agent-releases/releases/download/dev-v0.1.3-dev.2054/saw-agent_dev-v0.1.3-dev.2054_linux_arm64.tar.gz"
      sha256 "5e11cf9d7fd74734eb40c355e80289d58d8feb2eb24b5437b86ba6c782b43c3c"
    else
      url "https://github.com/LenderCom/saw-agent-releases/releases/download/dev-v0.1.3-dev.2054/saw-agent_dev-v0.1.3-dev.2054_linux_amd64.tar.gz"
      sha256 "95b34455031937fdaad471490e74ab85e1951eacb7b59759aacfdb86d7b79a40"
    end
  end

  # Named saw-agent-dev (not saw-agent) end to end — the shim on PATH, the keg, the class —
  # so it installs and links alongside the stable saw-agent formula without either
  # clobbering the other's /opt/homebrew/bin entry. One machine still runs one channel's
  # binary at a time in practice: whichever of the two you actually invoke is the one that
  # pairs, and its self-update writes the SAME ~/.saw/bin/saw-agent + ~/.saw/cloud/channel
  # the get.sawrun.com installer would (that installer has no dev/stable formula split —
  # it takes a --channel flag against one managed copy).
  def install
    libexec.install "saw-agent"
    (bin/"saw-agent-dev").write shim_script
    chmod 0755, bin/"saw-agent-dev"
  end

  def shim_script
    <<~SH
      #!/bin/bash
      # Generated by Formula/saw-agent-dev.rb — do not edit directly.
      managed="$HOME/.saw/bin/saw-agent"
      keg="#{opt_libexec}/saw-agent"

      # Same ENOEXEC footgun as the stable formula's shim (see Formula/saw-agent.rb) —
      # probe with a fast, side-effect-free flag before exec'ing the managed copy.
      if [ -x "$managed" ] && "$managed" -version >/dev/null 2>&1; then
        exec "$managed" "$@"
      fi

      exec "$keg" "$@"
    SH
  end

  def caveats
    <<~EOS
      DEV-CHANNEL build (#{version}), rebuilt several times a day — for use against a
      dev SAW workspace, not production.

      Set this machine up:

        saw-agent-dev setup

      It pairs, installs itself to start on boot, and walks you through the macOS
      permissions it needs — then asks two questions.

      Get the answers from your browser: open the dev SAW workspace, go to
      Settings -> Remote agents, and click "Add remote agent". The wizard shows the
      workspace id and a one-time pair code, in the order setup asks for them.

      The dev cloud origins are compiled in — nothing to export.

      Run `saw-agent-dev` (not `saw-agent`) — this installs alongside the stable
      formula under its own name.
    EOS
  end

  test do
    assert_match "saw-agent #{version}", shell_output("#{bin}/saw-agent-dev --version")
  end
end
