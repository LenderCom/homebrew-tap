class SawAgentDev < Formula
  desc "SAW remote agent - dev channel, tracks latest saw-agent-releases pre-release"
  homepage "https://github.com/LenderCom/saw-agent"
  version "0.1.2-dev.97+gc53fbc2"

  # Dev-channel builds cut several times a day from LenderCom/saw-agent-releases
  # (tags dev-vX.Y.Z-dev.N). .github/workflows/bump-formula-dev.yml keeps this pinned to
  # the latest one automatically — see that workflow + script/bump-formula.rb (shared with
  # the stable saw-agent formula; it takes the formula path as its third argument).
  on_macos do
    if Hardware::CPU.arm?
      url "https://github.com/LenderCom/saw-agent-releases/releases/download/dev-v0.1.2-dev.97/saw-agent_dev-v0.1.2-dev.97_darwin_arm64.tar.gz"
      sha256 "e77876f6660f254cc5e67b681aa7410d97b21b4c1cd93753a04f05d75e02da8a"
    else
      url "https://github.com/LenderCom/saw-agent-releases/releases/download/dev-v0.1.2-dev.97/saw-agent_dev-v0.1.2-dev.97_darwin_amd64.tar.gz"
      sha256 "d08e5e18ee168ff74942c616a55d75784d8e8d9126efeecd324eee87eceee149"
    end
  end

  on_linux do
    if Hardware::CPU.arm?
      url "https://github.com/LenderCom/saw-agent-releases/releases/download/dev-v0.1.2-dev.97/saw-agent_dev-v0.1.2-dev.97_linux_arm64.tar.gz"
      sha256 "119d594a368036dd8d261b4a3af5e8a5effc5259b1c9856ce2ca6b658e6b30ea"
    else
      url "https://github.com/LenderCom/saw-agent-releases/releases/download/dev-v0.1.2-dev.97/saw-agent_dev-v0.1.2-dev.97_linux_amd64.tar.gz"
      sha256 "929072657fd837fb94ce57690688435a46b707cb154fa54646475a94eb2cfe89"
    end
  end

  # Named saw-agent-dev (not saw-agent) end to end — the shim on PATH, the keg, the class —
  # so it installs and links alongside the stable saw-agent formula without either
  # clobbering the other's /opt/homebrew/bin entry. One machine still runs one channel's
  # binary at a time in practice: whichever of the two you actually invoke is the one that
  # pairs, and its self-update writes the SAME ~/.saw/bin/saw-agent + ~/.saw/cloud/channel
  # the get.sawrun.com installer would (that installer has no dev/stable formula split —
  # it takes a --channel flag against one managed copy).
  def install
    libexec.install "saw-agent"
    (bin/"saw-agent-dev").write shim_script
    chmod 0755, bin/"saw-agent-dev"
  end

  def shim_script
    <<~SH
      #!/bin/bash
      # Generated by Formula/saw-agent-dev.rb — do not edit directly.
      managed="$HOME/.saw/bin/saw-agent"
      keg="#{opt_libexec}/saw-agent"

      # Same ENOEXEC footgun as the stable formula's shim (see Formula/saw-agent.rb) —
      # probe with a fast, side-effect-free flag before exec'ing the managed copy.
      if [ -x "$managed" ] && "$managed" -version >/dev/null 2>&1; then
        exec "$managed" "$@"
      fi

      exec "$keg" "$@"
    SH
  end

  def caveats
    <<~EOS
      This is a DEV-CHANNEL pre-release build (#{version}), rebuilt from
      LenderCom/saw-agent-releases several times a day — expect it to move. It is for
      internal/dev use against a dev SAW cloud workspace, not production.

      Installs side by side with the stable `saw-agent` formula under its own name:
        - #{opt_bin}/saw-agent-dev is the dispatch shim (run this).
        - #{opt_libexec}/saw-agent is this keg's pinned, versioned binary.

      Next: pair this machine with a DEV SAW cloud workspace
      =======================================================

      1. Easiest — open the dev SAW workspace in the browser, go to Agents, and click
         "Add remote agent". The wizard mints a one-time pair code and hands you the
         exact command, already filled in.

      2. Direct — a workspace operator mints a code (`saw machines pair-code`, or the
         same wizard):

           SAW_CLOUD_ORG=<org-id> \\
             SAW_CLOUD_PAIR_CODE=<code> \\
             saw-agent-dev --cloud

      3. Self-pair your OWN signed-in machine — no code needed:

           SAW_CLOUD_SELF_PAIR=1 SAW_CLOUD_ORG=<org-id> saw-agent-dev --cloud

         (needs SAW_CLOUD_USER_TOKEN — a signed-in user session bearer)

      The compiled agent has NO built-in default cloud origin — against the DEV cloud
      you must export all four every time (this is true for the stable formula too;
      only the in-app wizard's copyable command fills them in for you), so set:

        SAW_CLOUD_AGENTS_URL=https://agents.dev.sawrun.com
        SAW_CLOUD_ACCOUNTS_URL=https://accounts.dev.sawrun.com
        SAW_CLOUD_REALTIME_URL=https://realtime.dev.sawrun.com
        SAW_CLOUD_WORKSPACE_URL=https://workspace.dev.sawrun.com

      Want production instead? `brew install lendercom/tap/saw-agent` (the stable
      formula) — same pairing flow, *.sawrun.com origins instead of *.dev.sawrun.com.

      `brew upgrade saw-agent-dev` picks up whatever dev-channel build
      .github/workflows/bump-formula-dev.yml last pinned — run `brew update` first if
      you want the very latest (it bumps on every new pre-release, on a short poll
      cadence until LenderCom/saw-agent-releases dispatches it directly).
    EOS
  end

  test do
    assert_match "saw-agent #{version}", shell_output("#{bin}/saw-agent-dev --version")
  end
end
